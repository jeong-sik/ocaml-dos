  | 0xF5 -> Some "...##... ...##... ...##... ...##... ...##... ##.##... ##.##... .###...." (* ⌡ *)
  | 0xF7 -> Some "........ .###.##. ##.###.. ........ .###.##. ##.###.. ........ ........" (* ≈ *)
  | 0xF9 -> Some "........ ........ ...##... ..####.. ...##... ........ ........ ........" (* ∙ *)
  | 0xFB -> Some "....#### ....##.. ....##.. ....##.. ###.##.. .##.##.. ..####.. ...###.." (* √ *)
  | 0xFC -> Some ".####... .##.##.. .##.##.. .##.##.. ........ ........ ........ ........" (* ⁿ *)
  | 0xFE -> Some "........ ........ ..####.. ..####.. ..####.. ..####.. ........ ........" (* ■ *)
  | _ -> None

(* 그림 한 행을 최하위 비트가 왼쪽인 바이트로. 그림이 틀리면 모듈을 싣는
   순간 멈춘다 — 표는 상수라 첫 테스트가 잡는다. *)
let parse_row ch row =
  if String.length row <> row_count then
    invalid_arg (Printf.sprintf "Font8x8_ext: 0x%02X row %S" ch row);
  let byte = ref 0 in
  String.iteri
    (fun i c ->
      if c = lit then byte := !byte lor (1 lsl i)
      else if c <> unlit then
        invalid_arg (Printf.sprintf "Font8x8_ext: 0x%02X row %S" ch row))
    row;
  !byte

let parse ch art =
  let rows = Array.of_list (List.map (parse_row ch) (String.split_on_char ' ' art)) in
  if Array.length rows <> row_count then
    invalid_arg (Printf.sprintf "Font8x8_ext: 0x%02X has %d rows" ch (Array.length rows));
  rows

let blank = Array.make row_count 0

let table =
  Array.init 256 (fun ch ->
      match (from_font8x8 ch, drawn ch) with
      | Some rows, None -> rows
      | None, Some art -> parse ch art
      | None, None -> blank
      | Some _, Some _ ->
        invalid_arg (Printf.sprintf "Font8x8_ext: 0x%02X is in both tables" ch))

let lsb_left ch = table.(ch land 0xff)
