let reverse_bits b =
  let r = ref 0 in
  for i = 0 to 7 do
    if b land (1 lsl i) <> 0 then r := !r lor (0x80 lsr i)
  done;
  !r

(* IBM 순서 — 최상위 비트가 왼쪽 점. *)
let glyph ch = Array.map reverse_bits (lsb_left ch)
