(* The BIOS keystroke words, by key. See dos_keymap.mli. *)

type modifier = Shift | Ctrl | Alt
type edge = Down | Up
type key = { scan : int; held : modifier option }

let break_bit = 0x80

let make_code = function Shift -> 0x2A | Ctrl -> 0x1D | Alt -> 0x38

